def _build_city_list() -> List[str]:
    names = set()
    for line in _CITY_RAW.strip().splitlines():
        line = normalize(line)
        if not line:
            continue
        # نام‌های چندبخشی از فهرست جداگانه می‌آیند؛ اینجا تک‌واژه‌ها را می‌گیریم
        for token in line.split():
            if len(token) >= 3:
                names.add(token)
    for m in _EXTRA_MULTIWORD:
        names.add(normalize(m))
    # ترکیب‌های دوکلمه‌ای پرکاربرد که در متن خام با فاصله آمده‌اند
    for combo in re.findall(r"[^\s]+ اباد", normalize(_CITY_RAW)):
        names.add(combo)
    return names and sorted(names, key=lambda s: (-len(s), s))


