# واژه‌هایی که تک‌واژه‌شان نباید شهر تلقی شود
_STOPWORDS = {
    "شهر", "شهرستان", "استان", "منطقه", "ناحیه", "طرح", "جامع", "تفصیلی",
    "مصوبه", "شورای", "عالی", "معماری", "شهرسازی", "ایران", "کشور", "غرب",
    "شرق", "شمال", "جنوب", "مرکزی", "اباد", "بندر", "دشت", "کرون", "گنج",
}

_CITY_ALT = "|".join(re.escape(c) for c in CITIES)

# الگوهای بافتی: «شهر X»، «شهرستان X»، «طرح جامع X»
_CONTEXT_PATTERNS = [
    re.compile(r"(?:طرح|طرح‌های)?\s*(?:جامع|تفصیلی|هادی|ویژه)\s+(?:شهر\s+)?(" + _CITY_ALT + r")(?!\S)"),
    re.compile(r"محدوده\s+(?:و\s+حریم\s+)?(?:شهر\s+)?(" + _CITY_ALT + r")(?!\S)"),
    re.compile(r"حریم\s+(?:شهر\s+)?(" + _CITY_ALT + r")(?!\S)"),
    re.compile(r"شهر\s+(" + _CITY_ALT + r")(?!\S)"),
    re.compile(r"شهرستان\s+(" + _CITY_ALT + r")(?!\S)"),
    re.compile(r"(?:کلانشهر|کلان شهر)\s+(" + _CITY_ALT + r")(?!\S)"),
]

_BARE_RE = re.compile(r"(?<![؀-ۿ])(" + _CITY_ALT + r")(?![؀-ۿ])")

_PROVINCE_ALT = "|".join(re.escape(p) for p in sorted(PROVINCES, key=len, reverse=True))
_PROVINCE_RE = re.compile(r"استان\s+(" + _PROVINCE_ALT + r")(?!\S)")


def extract_city(title: str, body: str = "", max_body_chars: int = 1500) -> Tuple[str, str]:
    """(شهر، روش تشخیص) را برمی‌گرداند؛ ابتدا از عنوان، سپس ابتدای متن."""
    for source, label in ((title, "عنوان"), (body[:max_body_chars], "متن")):
        norm = normalize(source)
        if not norm:
            continue
        for pattern in _CONTEXT_PATTERNS:
            m = pattern.search(norm)
            if m:
                name = m.group(1)
                if name not in _STOPWORDS:
                    return name, label
        # تطبیق مستقیم نام شهر بدون واژه بافتی
        for m in _BARE_RE.finditer(norm):
            name = m.group(1)
            if name not in _STOPWORDS and len(name) >= 3:
                return name, label + " (نام مستقیم)"
    return "", ""


def extract_province(title: str, body: str = "", city: str = "",
                     max_body_chars: int = 3000) -> str:
    """نام استان را از متن یا از روی مرکز استان تشخیص می‌دهد."""
    for source in (title, body[:max_body_chars]):
        m = _PROVINCE_RE.search(normalize(source))
        if m:
            return m.group(1)
    if city and city in PROVINCE_CAPITALS:
        return PROVINCE_CAPITALS[city]
    return ""


def is_known_city(name: str) -> bool:
    return normalize(name) in _CITY_SET


# ------------------------------------------------- مرتب‌سازی الفبای فارسی
# ترتیب کدهای یونیکد با ترتیب الفبای فارسی یکی نیست (مثلاً «پ» بعد از «ی»
# قرار می‌گیرد). این کلید، ترتیب درست الفبایی را تضمین می‌کند.
PERSIAN_ALPHABET = "اببپتثجچحخددذرزژسشصضطظعغفقکگلمنوهی"

_ALPHABET_ORDER = {ch: i for i, ch in enumerate(dict.fromkeys(PERSIAN_ALPHABET))}


def persian_sort_key(name: str):
    """کلید مرتب‌سازی بر پایه ترتیب الفبای فارسی."""
    norm = normalize(name)
    key = []
    for ch in norm:
        if ch in _ALPHABET_ORDER:
            key.append((0, _ALPHABET_ORDER[ch]))
        elif ch == " ":
            key.append((1, 0))
        else:
            key.append((2, ord(ch)))
    return key
